//! 主列的**纵向排布**：列表 / 详情 / 导入区 / 尾部谁和谁抢同一块高度（M361 / M374）。
//!
//! 横向三栏的几何在 [`super::layout`]（栏宽 + 四档），本文件只管**竖向**：同一列里谁拿 `Fill`、
//! 谁按自然高度铺、详情与导入区站在哪。
//!
//! ## 预算表
//!
//! ```text
//! 正文  = `frame::body_height`（窗口高 − 标题栏 48 − 页头 84 − 页边 2×24 − 提示条）
//! ├─ 列头  = `parts::head::plan` 的 `chrome`（≤ 281；含到第一张卡的那条 `Space::X2`）
//! └─ 主列  = 正文 − chrome
//!      ├─ 结果列表（自己滚）
//!      ├─ 详情（只在没有独立详情列的档里出现在这一列）
//!      └─ 尾部：加载更多 / 没有更多了
//! ```
//!
//! | 档 | 详情在哪 | 列表拿多高 | 导入区在哪（只有整合包有） |
//! |---|---|---|---|
//! | `Wide` / `Narrow`（有独立详情**列**） | 右侧那一栏，高 `Fill` | `Fill`：主列剩下的全给它 | `Split`：列表的滚动区；`ScrollWhole`：列头之上 |
//! | `Compact` / `Tight` + `Split` | **本文件**：接在结果行之后、与行**同一个**滚动区 | `Fill`：主列 − 尾部 | 列表的滚动区（M374） |
//! | `Compact` / `Tight` + `ScrollWhole` | 主列末尾（整列一个滚动区，M161 起的现状） | `Shrink`：自然高 | M358：纯入口排到结果之后，其余仍在列头之上 |
//!
//! ## 一条公式（M361 定，M374 补全）
//!
//! ```text
//! Split 档的列表视口（`Mod` / 资源包 / 光影 / 整合包 共用）：
//!     列表 = 正文 − chrome − Space::X2 − 尾部
//!           ≥ 460 − 281 − 8 − 40 = 131   （Split 的下限：正文正好 460、列头满额、尾部是按钮）
//! 一张整卡 = `head::one_card` = 三行档 76 + 行距 4 = 80  ⇒ 131 ≥ 80
//! ```
//!
//! 成立的前提是「主列里除列头与尾部之外**没有别的非 `Fill` 兄弟**」。iced 的 flex
//! （`iced_core::layout::flex::resolve`）分两遍走：先按自然高度把所有**非** `Fill` 子项排完，
//! 再把 `remaining = 区域 − Σ非 Fill 子项 − 间距` 按权重分给 `Fill` 子项，`remaining` 为负就
//! `max(0.0)` —— 列表因此可以正好变成 **0 高**。所以只要列表上下多挂一块**高度随数据变**的东西，
//! 它就可能是 0：详情是这样（M361 的 P1-1），导入区也是这样（M374）。
//!
//! 修法只有一种：**把那块东西移出 `Fill` 的预算** —— 交给列表，落进**同一个**滚动区。
//!
//! ## P1-1（M361）：详情和列表抢同一列 ⇒ 880×900 只剩 45、944×720 是 0
//!
//! 修前 `[列表(Fill), 分隔线, 详情, 尾部]` 挤在同一个 column 里，式子是
//! `列表 = 正文 − chrome − 3×X2 − 分隔线 − 详情 − 尾部`：
//!
//! ```text
//! 880×900：720 − 281 − 24 − 1 − 329 − 40 =  45   （实测 45，连一张卡 76 都不到）
//! 944×720：540 − 281 − 24 − 1 − 329 − 40 = −135 → 0（实测 0，一条结果都画不出来）
//! ```
//!
//! 详情那块 **329 不是常数**：它随标题/简介行数、版本条数（≤5）、目标实例、禁用原因逐条变化
//! ⇒ 修前的式子里有一个**没有上界**的减数。修法见 [`detail_in_list_scroll`]。
//!
//! **代价（明写，复审 r1 P2-2 补充）**：详情块（含「装入」按钮）不再是首屏常驻 —— 一是要滚到
//! 列表末尾才看到（`Select` 会自动把它滚进视野，见 [`super::parts::snap_to_detail`]），二是每点
//! 一次「加载更多」（append，`PAGE = 20`）详情就再往下退一页（1,600px ≈ 4 个视口 / 8 个视口）。
//! 这个取舍与 M358 给导入区定的规则同源（「用户此刻要看的结果」优先）。换成「给详情一个固定高
//! 上限」会在**详情很短**时（未选中 = 一行 16px）白占几百像素、把列表压到只剩一张卡，所以没选它。
//!
//! ## M374：导入区是同一类的减数（`Modpack` + `Split`，11-05 登记的旧 bug）
//!
//! 修前 `Modpack` 的导入/导出区排在**列头之上**（`pack_before_results` 对 `Split` 恒为真），
//! 于是列表的式子里再多一个减数：
//!
//! ```text
//! 修前：列表 = 正文 − chrome − X2 − 尾部 − (导入区 + 分隔线 1 + 2×X2)
//! 880×900（导入区 329）：720 − 281 − 8 − 40 − (329 + 1 + 16) =  45（实测首卡带 783..827 = 45，被切）
//! 944×720（导入区 329）：540 − …                              = −135 → 0（实测一条结果带都没有，
//!                                                              连列头都被挤出正文：列头之前就要 329 + 17 + 281 = 627 > 540）
//! 1180×900（导入区 289）：720 − …, 只有 84px
//! ```
//!
//! **「导入区最多能占多少」是算出来的**：要让列表 ≥ 一张整卡 80，
//!
//! ```text
//! 导入区 ≤ 正文 − chrome − X2 − 尾部 − (1 + 2×X2) − 80
//! 880×900（正文 720）：720 − 281 − 8 − 40 − 17 − 80 = 294
//! 944×720（正文 540）：540 − …                     = 114
//! Split 的下限（正文 460）：460 − …                 =  34   ← 最紧的那一档
//! ```
//!
//! 那个「导入区」是**宽度相关**的 289（1180 宽）/ 329（880、944 宽），不是常量。三个候选：
//!
//! | 候选 | 880×900 | 944×720 | Split 下限 460 | 结论 |
//! |---|---|---|---|---|
//! | ① 导入区并入列表的滚动区（**采用**） | 391 | 211 | 131 | 与 `Mod` 族共用一条公式，任何尺寸都 ≥ 80 |
//! | ② 给导入区一个高度上限 | 上限 ≤ 294 | ≤ 114 | **≤ 34** | 下限那一档装不下 34（拖拽区本身 68），判据必红 |
//! | ③ 调换顺序（结果先于导入） | 45 | 0 | −135 | **算式一分不变**，见下 |
//!
//! ③ 最容易误判：换序只改「谁先被看到」，不改「谁占高度」——`Fill` 子项拿到的永远是「扣完所有
//! 非 `Fill` 兄弟」之后的剩余，所以只要那块区还在主列的兄弟里，列表就还是 45 / 0。
//!
//! 所以修法还是「移出预算」：`Split` 档把导入区交给列表（[`pack_in_list_scroll`]），位置仍按
//! [`pack_before_results`] 的两档：
//!
//! | 那块区的状态 | 在滚动区里的位置 | 为什么 |
//! |---|---|---|
//! | 纯入口（`is_entry_only`） | 结果行**之后**、详情尾块**之前** | 与 M358 给矮窗定的规则同源：用户此刻要看的是结果。详情尾块必须留在**最后**一块，`snap_to(END)` 才落在详情上 |
//! | 进行中 / 待决策 / 有结果 | 结果行**之前** | 那是用户此刻要做的事，滚到顶就在；顺带修掉「冲突清单 / 导出预检把动作按钮顶出屏幕」（`Split` 档正列没有整页滚动，见 `packui::view::section` 的注释） |
//!
//! `ScrollWhole` 档（矮窗）一切照旧：主列本来整列在滚，M358 的排法与基线图一个像素不许动。
//!
//! **代价（明写）**：纯入口态下导入区不再首屏常驻。演示夹具（4 条结果）里它在列表滚动区一屏
//! 之内（4×80 + 8 ⇒ 首屏下方约 330px，滚一下就到）；**满一页**（`PAGE = 20`，20×80 = 1,600）时
//! 它在首屏下方约 **4 个视口**（880×900 视口 391）/ **8 个**（944×720 视口 211）。不选「导入区
//! 留在结果之前」正是因为那样首屏又一张卡都看不到 —— 那正是本条要修的现场。
//!
//! **另一条代价**：`Modpack` + `Wide` / `Narrow` 的导入区也跟着进了滚动区（那里列表同样是 `Fill`，
//! 同一个病）⇒ 那两档的整合包首屏变成「结果在前、导入区在列表末尾」。没有基线图钉那两档的整合包
//! （1180×900 / 1024×760 的锚图是 `Mod` 族），像素对照在 `DevDocs/artifacts/modpackzero/`。

use super::layout::{pack_before_results, BodyMode, Tier};

/// `Split` 档里，详情块和结果列表共用**同一个**滚动区吗（M361）。
///
/// 判据只有两个入参，都不读数据状态：档位有没有独立详情列、主列是不是 `Split`。
#[must_use]
pub(super) const fn detail_in_list_scroll(tier: Tier, mode: BodyMode) -> bool {
    // `!has_detail` 决定「同一列」，`list_scrolls` 决定「列表拿 `Fill`」——两个条件各自的作用
    // 见模块文档。少一个都不会挤成 0，也就不必改排法（改了反而动到基线）。
    !tier.has_detail() && mode.list_scrolls()
}

/// `Split` 档里，导入/导出区也进列表那**同一个**滚动区吗（M374）。
///
/// 只看「列表是不是 `Fill`」，不看档位：`Wide` / `Narrow` 的详情在右侧独立列，列表照样是 `Fill`，
/// 那块区照样把列表压下去（1180×900 实测只剩 85）——同一个病，同一处修。
/// **它只是这条判据的一半**：列表没画出来时不能把区交给滚动区（那时整块会消失），
/// 那一半在 [`pack_place`] 里（`ready` 入参）。
#[must_use]
pub(super) const fn pack_in_list_scroll(mode: BodyMode) -> bool {
    mode.list_scrolls()
}

/// 导入/导出区在主列里的落点（M358 定的位置 + M374 定的归属，**一处算出**）。
///
/// 这一条是本条（M374 r2，复审 P1-1）的唯一真相源：上一版把「进不进滚动区」写在 `view.rs` 的
/// 两个布尔里，于是 `Split` + 非 `Ready` 时那块区**两头都不在**（`pack_above` 与 `pack_below`
/// 双双为假，而滚动区那一份只在 `Ready` 分支里创建）⇒ 搜索框每敲一下它就闪掉，
/// 0 结果 / 离线页上一直不在。改成「四态都算得出落点」的纯函数之后，那种漏洞是类型级的。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum PackPlace {
    /// 这一类内容没有这块区（只有整合包有）
    Absent,
    /// 列头**之上**：`ScrollWhole` 的非纯入口（M358），或 `Split` 但**列表没画**（退回 M374 之前的
    /// 排法 —— 那时列表没上屏，那块区挤不到任何东西）
    AboveHead,
    /// 列表滚动区里、结果行**之前**（进行中 / 待决策 / 有结果：用户此刻要做的事）
    ScrollLead,
    /// 列表滚动区里、结果行**之后**（纯入口：用户此刻要看的是结果）
    ScrollTail,
    /// 主列末尾（结果与尾部之后）：`ScrollWhole` + 纯入口，M358 起的排法
    BelowBody,
}

impl PackPlace {
    /// 这块区排在列头**之上**吗（`has_pack == false` 时为假）。
    ///
    /// 单独给一个名字是因为调用侧只需要这一问（`view.rs` 的 `if`），而判据要问的是整张表。
    #[must_use]
    pub(super) const fn is_above_head(self) -> bool {
        matches!(self, Self::AboveHead)
    }
}

/// 导入/导出区这一帧落在哪。
///
/// 四个入参都是**纯值**（没有 `Element`、没有 `&Content`），所以「四态 × 两档 × 两种状态」
/// 整张表都测得到：
///
/// ```text
/// !has_pack                                  ⇒ Absent
/// Split + ready      + 纯入口                 ⇒ ScrollTail（结果之后、详情之前）
/// Split + ready      + 进行中/待决策/有结果     ⇒ ScrollLead（结果之前）
/// Split + !ready     + 任意                   ⇒ AboveHead  ← 这一格是 r1 的 P1（整块消失）
/// !Split + 纯入口                             ⇒ BelowBody（M358：矮窗排到结果之后）
/// !Split + 进行中/待决策/有结果                 ⇒ AboveHead（M358：仍在顶部）
/// ```
///
/// `ready` = 「结果列表真的在画」，来自
/// [`parts::status_body`](super::parts::status_body)`(..).is_none()`（只有 `Ready` 给 `None`）。
#[must_use]
pub(super) const fn pack_place(
    has_pack: bool,
    entry_only: bool,
    mode: BodyMode,
    ready: bool,
) -> PackPlace {
    let leads = pack_before_results(has_pack, entry_only);
    if !has_pack {
        PackPlace::Absent
    } else if pack_in_list_scroll(mode) && ready {
        if leads {
            PackPlace::ScrollLead
        } else {
            PackPlace::ScrollTail
        }
    } else if !mode.list_scrolls() && !leads {
        PackPlace::BelowBody
    } else {
        PackPlace::AboveHead
    }
}
