//! Linux（X11 / Wayland）的窗口圆角（M182）：**谁负责、我们为什么不画**。
//!
//! 用户定的规则是「非 Windows 按窗口合成器的默认规则来」。在 Linux 上这句话要落到具体机制，
//! 否则很容易变成「把 Windows 那套 DWM 判据搬过来假装能用」——**不许**那样写（M182 任务书）。
//!
//! ## 事实层：协议里没有「圆角」这个概念
//!
//! | 层 | 有什么 | 依据级别 |
//! |---|---|---|
//! | `xdg-shell`（Wayland） | 只有 `wl_surface.set_opaque_region` / `set_input_region`（**矩形集合**）、`set_buffer_transform`、圆角半径之类一概没有 | A 级（协议规范） |
//! | X11 | 形状扩展（`XShape`）能按矩形并集切出非矩形窗口，但**只能切硬边**（无抗锯齿）；要透明圆角得配 ARGB visual + 合成器 | A 级（X 扩展规范） |
//! | 装饰归属 | 谁装饰谁负责：合成器画（SSD）由合成器圆，客户端画（CSD）由客户端圆。`zxdg_decoration_manager_v1` **很多合成器即使被请求也不画**（D35 已记） | A 级协议 + D35 实测/推断 |
//!
//! 我们是 **CSD**：`decorations: false`（`app/boot/diagnostics.rs`），自绘标题栏 + 自绘三键。
//! 所以「圆角该由谁画」的答案是**我们**——而 D46 第 4 条明确要求不自绘裁切，
//! 于是唯一的诚实结果是**直角**，并把这句结论写进日志：
//! `source=compositor excluded_reason=client-side`（见 [`crate::platform::win32::corner`]）。
//!
//! ## 为什么不自绘（不是「懒得做」）
//!
//! 1. 自绘圆角 = 把内容层裁成圆角。我们的内容层含**自绘三键 + 边缘缩放热区**，裁掉圆角就会
//!    一起裁掉热区（这条在 M116 已被 tower 采纳）。
//! 2. Wayland 上「表面画圆角 + ARGB 缓冲」在合成器侧确实能透出桌面，但需要整窗 `transparent`
//!    ——那是 D36 的整窗 α 管线，且会与 Linux 上「没有 `_NET_WM_CM_S0` 合成器时透明变黑」的
//!    既有结论打架。
//! 3. X11 无合成器时透明不可用；只剩 `XShape` 硬边圆角——像素级毛边，比直角更难看。
//!
//! ## 合成器差异（**推断级，本机无真机，未验**）
//!
//! - 浮动式合成器（KWin / Mutter）对自己的 SSD 窗做圆角，对 CSD 窗**通常不裁**（客户端的 surface
//!   原样合成）；但个别主题会给无边框窗额外加重绘制的阴影/边框——那种圆角是**合成器画的**，
//!   不是我们画的。判别口径：日志 `source=compositor`，而像素上的圆角随主题/合成器变化。
//! - 平铺式（sway / niri / Hyprland / river）连边框都按自己的配置画，更不会替 CSD 窗裁圆角；
//!   D35/D37 还记着「sway 默认下已经出现合成器 SSD + 我们自绘的双标题栏」这条现状缺陷。
//!
//! 这些行为**没有任何一条**能用协议查询，也没有一条能由应用侧读取——所以判据里**不写**
//! 「Linux 会/不会圆角」，只写「决定权在合成器，而 CSD 窗它不裁」。
//!
//! ## 本轮明确未验
//!
//! - 真实合成器上的四角观感（无 Linux 真机；CI 的 Linux 冒烟只验「能起来 + 出图不是全黑」）；
//! - KWin / Mutter / Hyprland 是否会对我们的 CSD 窗做额外装饰；
//! - 高 DPI 下若将来改为自绘，半径是否需要缩放（本轮不涉及：半径不由我们定）。
