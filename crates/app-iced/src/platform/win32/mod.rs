//! Win32 专属的窗口能力。
//!
//! | 子模块 | 是什么 | 有没有 `unsafe` |
//! |---|---|---|
//! | [`transparency`] | D36 定案的整窗 α 唯一实现落点（也是 M116 的 DWM 圆角落点） | **有**（全仓唯一） |
//! | [`corner`] | M116 的圆角**判据**：策略 × 系统版本 × 渲染档 → 来源与原因码 | 没有（纯函数） |
//!
//! 目录形态（而非 `win32.rs` 单文件）是为了让「每个平台一份实现」在路径上一眼可见：
//! 将来 macOS / Wayland 的对应能力各自成目录，互不干扰。
//!
//! **非 Windows 平台也在编译**：`transparency` 里的公开函数有同签名的空实现，
//! `corner` 的判据在探测不到系统版本时给出「直角 + `unknown-os`」，所以调用点不需要 `#[cfg]`，
//! 行为（返回「本平台不支持」）可被测试断言。

pub mod corner;
pub mod transparency;
