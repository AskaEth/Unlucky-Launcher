//! # 界面语言入口（M106 `I18NFOLLOW`）
//!
//! 用户报的原话：「我系统语言是中文 为什么打开软件是英文 并且设置页里面显示的是 English (System)」。
//! 前半是**探测对了但没人用**（`app/view.rs` 里 `Lang::En` 写死），后半是一行硬编码假值。
//!
//! 这个模块就是那条缺失的入口：把「用户选的档位 + M92 的探测结论」变成一个值，交给
//! `pages::Model.lang`（目录）与设置页语言行（档位回显）。
//!
//! | 文件 | 是什么 |
//! |---|---|
//! | [`lang`] | [`lang::LangState`]：启动判定（`ULL_LANG` > 配置 > 系统 locale > 英文）、切档、两行日志 |
//!
//! 为什么不叫 `theme::Ui` 的字段：`theme.rs` 是令牌求值器（颜色/字号/间距），语言不是令牌——
//! 它是**运行期状态**，随设置变化，还要落盘。混进 `Ui` 会让「切主题」与「切语言」共享一条重建路径，
//! 而它们该重建的东西根本不是同一批（一个重建 Style，一个重建视图模型）。

pub mod lang;
